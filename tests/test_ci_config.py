"""The build is reproducible: the lock file covers the dependencies, pre-commit and CI versions match it."""
import re
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "requirements-lock.txt"


def _requirements(path: Path) -> list[Requirement]:
    """Lines of a requirements file, following -r; comments and empty lines are skipped."""
    out: list[Requirement] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#")[0].strip()
        if line.startswith("-r"):
            out += _requirements(path.parent / line.split()[1])
        elif line:
            out.append(Requirement(line))
    return out


def _locked() -> dict[str, str]:
    pins = {}
    for req in _requirements(LOCK):
        spec = next(iter(req.specifier), None)
        assert spec is not None and spec.operator == "==", f"not an exact version in the lock file: {req}"
        pins[canonicalize_name(req.name)] = spec.version
    return pins


def test_lock_pins_every_requirement_within_bounds():
    locked = _locked()
    for req in _requirements(ROOT / "requirements-dev.txt"):
        name = canonicalize_name(req.name)
        assert name in locked, f"{req.name} is missing from requirements-lock.txt"
        assert req.specifier.contains(locked[name]), f"{req.name}=={locked[name]} does not fit {req.specifier}"


def test_lock_is_pip_compile_output():
    # Dependabot rebuilds only pip-compile files as a whole; otherwise it bumps versions one line at a time,
    # without resolving dependencies (a package can then end up outside the range another one requires)
    assert "autogenerated by pip-compile" in LOCK.read_text(encoding="utf-8")
    assert "-r requirements-dev.txt" in (ROOT / "requirements-lock.in").read_text(encoding="utf-8")


def test_precommit_ruff_matches_lock():
    config = (ROOT / ".pre-commit-config.yaml").read_text(encoding="utf-8")
    rev = re.search(r"ruff-pre-commit\n(?:\s*#[^\n]*\n)*\s*rev: v?([\d.]+)", config)
    assert rev, "no ruff-pre-commit in .pre-commit-config.yaml"
    assert rev.group(1) == _locked()["ruff"]


def test_ci_uses_lock_windows_and_audit():
    ci = (ROOT / ".github/workflows/ci.yml").read_text(encoding="utf-8")
    assert "pip install -r requirements-lock.txt" in ci
    assert "windows-latest" in ci and "ubuntu-latest" in ci
    assert "pip-audit" in ci
